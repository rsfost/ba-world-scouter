// Regenerates src/lib/world-regions.ts from RuneLite's world list.
//   node scripts/gen-world-regions.mjs
//
// The API base embeds the current client version, so the URL is resolved from
// RuneLite's bootstrap rather than hardcoded. Run this whenever Jagex adds
// worlds; unlisted worlds simply render without a flag.
//
// The world list only says a world is in the US. The east/west coast split
// comes from a game-cache enum, read by the Java tool in tools/world-locations,
// so this needs a JDK (11+) on the PATH.
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const BOOTSTRAP_URL = 'https://static.runelite.net/bootstrap.json';
const OUT = new URL('../src/lib/world-regions.ts', import.meta.url);
const TOOL_DIR = fileURLToPath(new URL('../tools/world-locations/', import.meta.url));

// Jagex location ids, as carried by the world list. Correlated against the
// country column of https://oldschool.runescape.com/slu; these are the same
// eight regions the RuneLite plugin draws flags for.
const REGIONS = {
  0: 'us',
  1: 'uk',
  3: 'aus',
  7: 'ger',
  8: 'br',
  9: 'jp',
  10: 'sg',
  12: 'za',
};

// Values of the cache's world location enum, matching the plugin's
// LOCATION_US_EAST / LOCATION_US_WEST.
const US_COASTS = {
  [-42]: 'us_east',
  [-73]: 'us_west',
};

async function json(url) {
  const resp = await fetch(url);
  if (!resp.ok) throw new Error(`GET ${url} failed (http ${resp.status})`);
  return resp.json();
}

function worldLocations() {
  const gradlew = process.platform === 'win32' ? 'gradlew.bat' : './gradlew';
  const stdout = execFileSync(gradlew, ['-q', 'run'], {
    cwd: TOOL_DIR,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    shell: process.platform === 'win32',
  });
  return JSON.parse(stdout);
}

const { version } = await json(BOOTSTRAP_URL);
if (!version) throw new Error('bootstrap.json has no client version');

const { worlds } = await json(`https://api.runelite.net/runelite-${version}/worlds.js`);
const cache = worldLocations();

// A US world the enum doesn't place keeps the plain US flag.
const unsplit = [];

const entries = worlds
  .map((world) => {
    const region = REGIONS[world.location];
    if (region !== 'us') return [world.id, region];
    const coast = US_COASTS[cache.locations[world.id]];
    if (!coast) unsplit.push(world.id);
    return [world.id, coast ?? region];
  })
  .filter(([, region]) => region !== undefined)
  .sort((a, b) => a[0] - b[0]);

const skipped = worlds.length - entries.length;
const body = entries.map(([id, region]) => `  ${id}: '${region}',`).join('\n');

await writeFile(
  OUT,
  `// Generated by scripts/gen-world-regions.mjs from RuneLite's world list
// (client ${version}, ${entries.length} worlds) and OpenRS2 cache ${cache.cache}
// (${cache.timestamp}). Do not edit by hand.
import type { RegionCode } from './flags';

export const WORLD_REGIONS: Readonly<Record<number, RegionCode>> = {
${body}
};
`,
);

console.log(`wrote ${entries.length} worlds${skipped ? ` (skipped ${skipped} with an unknown location)` : ''}`);
if (unsplit.length) {
  console.warn(`no east/west location in cache ${cache.cache} for US worlds: ${unsplit.join(', ')}`);
}
